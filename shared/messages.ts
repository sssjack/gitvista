let current: AppLanguage = 'en';

export function setMessageLanguage(language: AppLanguage): void { current = language === 'zh' ? 'zh' : 'en'; }

function fill(template: string, values: unknown[]): string {
  return template.replace(/\{(\d+)\}/g, (match, index) => {
    const value = values[Number(index)];
    return value === undefined ? match : String(value);
  });
}

/**
 * 按语言翻译一段中文原文。
 * 渲染进程显式传入语言（随界面状态变化），主进程用 msg/msgf 读取已保存的偏好。
 */
export function translate(language: AppLanguage, text: string, ...values: unknown[]): string {
  if (language === 'zh') return fill(text, values);
  const template = EN[text];
  return fill(template === undefined ? text : template, values);
}

/** 中文模式下返回原文；英文模式下查表，未登记时回退原文。 */
export function msg(text: string): string {
  return current === 'zh' ? text : EN[text] || text;
}

/** 带参数的翻译，用于拼接后的提示，例如“引用：{0}”。 */
export function msgf(text: string, ...values: unknown[]): string {
  return translate(current, text, ...values);
}
